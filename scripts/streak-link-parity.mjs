/**
 * Emit the transfer page's streak links as Swift test vectors.
 *
 * The page at /transfer writes `peachofaword://streak?...` links, and the app
 * parses them (`StreakTransfer.swift`). The links are pinned in
 * src/transfer/streakLinks.fixture.json, which src/transfer/streak.test.ts
 * holds the web's writer to. This writes the same rows into the Swift suite,
 * where StreakTransferTests parses each one.
 *
 * Nothing keeps the two copies in step but this script: change the fixture,
 * run it, and commit the Swift file it writes in the iOS repo.
 *
 * Run from the web repo root:
 *   node scripts/streak-link-parity.mjs > ../peach-of-a-word-swift/Tests/PeachEngineTests/StreakLinkVectors.swift
 */
import { readFileSync } from 'node:fs';

const fixture = JSON.parse(
  readFileSync('src/transfer/streakLinks.fixture.json', 'utf8'),
);

const rows = fixture.links.map(
  ({ link, count, lastClearedDayIndex }) =>
    `    StreakLinkVector(link: "${link}", count: ${count}, lastClearedDayIndex: ${lastClearedDayIndex}),`,
);

process.stdout
  .write(`// GENERATED by scripts/streak-link-parity.mjs in the web repo. Do not edit by hand.
//
// The streak links the web's transfer page writes, from its shared fixture,
// src/transfer/streakLinks.fixture.json. The web's own test holds its writer to
// the same rows. StreakTransferTests parses each link here.

import Testing

struct StreakLinkVector: Sendable, CustomTestStringConvertible {
    let link: String
    let count: Int
    let lastClearedDayIndex: Int

    var testDescription: String { link }
}

let streakLinkVectors: [StreakLinkVector] = [
${rows.join('\n')}
]
`);
