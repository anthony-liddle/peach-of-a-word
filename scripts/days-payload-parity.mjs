/**
 * Emit the transfer page's days payloads as Swift test vectors.
 *
 * The page writes "Peach of a Word days: " and base64url of a JSON body for the
 * app to paste, and the app parses it (`DaysTransfer.swift`). The payloads are
 * pinned in src/transfer/daysPayloads.fixture.json, which
 * src/transfer/days.test.ts holds the web's writer to. This writes the same
 * rows into the Swift suite, with what each one should parse to, where
 * DaysTransferTests reads each text.
 *
 * Nothing keeps the two copies in step but this script: change the fixture,
 * run it, and commit the Swift file it writes in the iOS repo.
 *
 * Run from the web repo root:
 *   node scripts/days-payload-parity.mjs > ../peach-of-a-word-swift/Tests/PeachEngineTests/DaysPayloadVectors.swift
 */
import { readFileSync } from 'node:fs';

const fixture = JSON.parse(
  readFileSync('src/transfer/daysPayloads.fixture.json', 'utf8'),
);

const swiftList = (words) => `[${words.map((w) => `"${w}"`).join(', ')}]`;

const rows = fixture.payloads.map(({ name, text, json }) => {
  const body = JSON.parse(json);
  const days = Object.entries(body.days)
    .map(
      ([day, { sourceWord, found }]) =>
        `            (${day}, "${sourceWord}", ${swiftList(found)}),`,
    )
    .join('\n');
  const streak = body.streak
    ? `(count: ${body.streak.count}, lastClearedDayIndex: ${body.streak.lastClearedDayIndex})`
    : 'nil';
  return `    DaysPayloadVector(
        name: "${name}",
        text: "${text}",
        streak: ${streak},
        days: [
${days}
        ]
    ),`;
});

process.stdout
  .write(`// GENERATED by scripts/days-payload-parity.mjs in the web repo. Do not edit by hand.
//
// The days payloads the web's transfer page writes, from its shared fixture,
// src/transfer/daysPayloads.fixture.json, with what each one carries. The web's
// own test holds its writer to the same rows. DaysTransferTests parses each
// text here.

import Testing

struct DaysPayloadVector: Sendable, CustomTestStringConvertible {
    let name: String
    let text: String
    let streak: (count: Int, lastClearedDayIndex: Int)?
    let days: [(Int, String, [String])]

    var testDescription: String { name }
}

let daysPayloadVectors: [DaysPayloadVector] = [
${rows.join('\n')}
]
`);
